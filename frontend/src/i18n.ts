export function translateValue(lang: Lang, v: string | null | undefined): string {
  if (v === null || v === undefined || v === "") return "—";
  const e = VALUES[v];
  return e ? e[lang === "ar" ? 1 : 0] : v.replace(/_/g, " ");
}

export interface I18n {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (k: TKey) => string;
  v: (value: string | null | undefined) => string;
}

export const I18nContext = createContext<I18n>({
  lang: "en",
  setLang: () => undefined,
  t: (k) => translate("en", k),
  v: (x) => translateValue("en", x),
});

export function useI18n(): I18n {
  return useContext(I18nContext);
}

const STORAGE_KEY = "tarbiyah_ui_lang";

export function loadLang(): Lang {
  try {
    const v = window.localStorage.getItem(STORAGE_KEY);
    if (v === "ar" || v === "en") return v;
  } catch {
    /* storage unavailable */
  }
  return "en";
}

export function storeLang(l: Lang): void {
  try {
    window.localStorage.setItem(STORAGE_KEY, l);
  } catch {
    /* storage unavailable */
  }
}

export function applyDocumentLang(l: Lang): void {
  document.documentElement.lang = l;
  document.documentElement.dir = l === "ar" ? "rtl" : "ltr";
}
